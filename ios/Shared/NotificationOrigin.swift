import Foundation

/// Optional sender metadata. IDs provide identity; names are only display labels.
struct NotificationOrigin: Codable, Hashable, Sendable {
    var workspace: String?
    var workspaceId: String?
    var session: String?
    var sessionId: String?

    var sessionLabel: String? {
        if let name = Self.nonempty(session) { return name }
        if let id = Self.nonempty(sessionId) {
            let short = id.count <= 12 ? id : String(id.prefix(8)) + "…" + id.suffix(4)
            return String(localized: "Session") + " · " + short
        }
        return nil
    }

    var workspaceLabel: String? { Self.nonempty(workspace) }
    var workspaceIdentity: String { Self.nonempty(workspaceId) ?? workspaceLabel ?? "" }
    var sessionIdentity: String { Self.nonempty(sessionId) ?? Self.nonempty(session) ?? "" }
    var searchText: String { [workspace, workspaceId, session, sessionId].compactMap { $0 }.joined(separator: "\n") }

    static func nonempty(_ value: String?) -> String? {
        guard let value = value?.trimmingCharacters(in: .whitespacesAndNewlines), !value.isEmpty else { return nil }
        return value
    }
}

extension MeowNotification {
    var compactHeadline: String {
        if let session = context?.sessionLabel { return session }
        // Event names are classification, never a fallback session headline.
        return event == nil ? inboxTitle : String(localized: "Session")
    }

    var compactMetadata: String {
        let agent = NotificationOrigin.nonempty(source) ?? "Meow"
        return [context?.workspaceLabel, agent].compactMap { $0 }.joined(separator: " · ")
    }

    var originSummary: String {
        [source.isEmpty ? "Meow" : source, context?.workspaceLabel].compactMap { $0 }.joined(separator: " · ")
    }

    /// Remove only the exact folder suffix generated by Meow hooks. Legacy
    /// messages have no context, and arbitrary custom titles are left alone.
    var inboxTitle: String {
        guard let workspace = context?.workspaceLabel else { return title }
        let suffix = " · " + workspace
        guard title.hasSuffix(suffix), title.count > suffix.count else { return title }
        return String(title.dropLast(suffix.count))
    }
}

/// Pure, deterministic colors shared by the list and detail avatar. Workspace
/// hues stay within an agent family; sessions vary tone within their workspace.
struct OriginColor: Equatable {
    let hue: Double
    let saturation: Double
    let brightness: Double
    let red: Double
    let green: Double
    let blue: Double

    init(source: String, context: NotificationOrigin) {
        let agent = source.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        let base: Double
        switch agent {
        case "codex": base = 0.61
        case "claude code", "claude": base = 0.07
        default: base = Self.fraction(agent)
        }
        let workspace = context.workspaceIdentity
        let workspaceHue = base + (workspace.isEmpty ? 0 : (Self.fraction(agent + "\u{0}" + workspace) - 0.5) * 0.09)
        hue = workspaceHue - floor(workspaceHue)
        let session = context.sessionIdentity
        let tone = session.isEmpty ? 0.5 : Self.fraction(agent + "\u{0}" + workspace + "\u{0}" + session)
        saturation = 0.62 + tone * 0.25
        brightness = 0.66 + (1 - tone) * 0.12
        let sector = hue * 6
        let chroma = brightness * saturation
        let x = chroma * (1 - abs(sector.truncatingRemainder(dividingBy: 2) - 1))
        let m = brightness - chroma
        let rgb: (Double, Double, Double)
        switch Int(sector) {
        case 0: rgb = (chroma, x, 0)
        case 1: rgb = (x, chroma, 0)
        case 2: rgb = (0, chroma, x)
        case 3: rgb = (0, x, chroma)
        case 4: rgb = (x, 0, chroma)
        default: rgb = (chroma, 0, x)
        }
        var channels = [rgb.0 + m, rgb.1 + m, rgb.2 + m]
        // White avatar initials maintain at least 4.5:1 contrast, including
        // yellow/green hues; the same solid fill is used in light and dark mode.
        while Self.luminance(channels) > 0.18 { channels = channels.map { $0 * 0.95 } }
        red = channels[0]; green = channels[1]; blue = channels[2]
    }

    private static func fraction(_ text: String) -> Double {
        var hash: UInt32 = 2_166_136_261
        for byte in text.utf8 { hash = (hash ^ UInt32(byte)) &* 16_777_619 }
        // Avalanche the final hash so adjacent session IDs produce distinct tones.
        hash ^= hash >> 16; hash = hash &* 0x85ebca6b
        hash ^= hash >> 13; hash = hash &* 0xc2b2ae35
        hash ^= hash >> 16
        return Double(hash) / Double(UInt32.max)
    }

    private static func luminance(_ rgb: [Double]) -> Double {
        let linear = rgb.map { $0 <= 0.04045 ? $0 / 12.92 : pow(($0 + 0.055) / 1.055, 2.4) }
        return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]
    }
}
